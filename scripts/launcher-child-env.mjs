function childEnvironment(names = []) {
  return Object.fromEntries([...systemNames, ...names]
    .filter(name => process.env[name] !== undefined).map(name => [name, process.env[name]]));
}

export const launcherSystemEnvironment = () => childEnvironment();
export const launcherRuntimeEnvironment = () => childEnvironment([...runtimeNames, ...browserNames]);
export const launcherBrowserEnvironment = () => childEnvironment(browserNames);
export const launcherBuildEnvironment = () => childEnvironment(buildNames);
export const launcherOllamaEnvironment = () => childEnvironment(ollamaNames);
export const launcherNativeEnvironment = () => childEnvironment([...runtimeNames, ...nativeNames]);
