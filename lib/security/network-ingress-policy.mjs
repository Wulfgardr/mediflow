export function allowsNetworkIngress(method, target) {
    if (typeof target !== 'string' || !target.startsWith('/')) return false;
    const pathname = target.split('?')[0];
    let segments;
    try { segments = pathname.split('/').map(decodeURIComponent); } catch { return false; }
    if (segments.some(segment => segment === '.' || segment === '..' || /[\\/\x00-\x20?#]/u.test(segment))) return false;
    return networkIngressRoutes.some(([route, methods]) => {
        if (!methods.split(',').includes(method)) return false;
        const expected = route.split('/');
        return expected.length === segments.length && expected.every((part, index) =>
            part.startsWith('[') ? Boolean(segments[index]) : part === segments[index]);
    });
}
