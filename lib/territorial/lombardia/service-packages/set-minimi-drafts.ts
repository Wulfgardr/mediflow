import {
    LOMBARDIA_SERVICE_CODE_SYSTEM,
    LOMBARDIA_SERVICE_PACKAGE_SCHEMA,
    type DocumentSource,
    type DraftServicePackage,
    type DraftServicePackageItem,
    type ServicePrescriptionCategory,
} from './contract';
import { NOMENCLATORE_2025 } from './diabetes-type2';

const SET_MINIMI_DOCUMENT = 'Set minimi III Gruppo di Lavoro regionale PAI su SGDT, conversione al nuovo nomenclatore (documento di lavoro)';
const SET_MINIMI_DATE = '2026-02-06';

function setMinimiSource(sectionOrTable: string): DocumentSource {
    return {
        kind: 'documento',
        document: SET_MINIMI_DOCUMENT,
        sectionOrTable,
        publishedAt: SET_MINIMI_DATE,
        status: 'documento_di_lavoro',
    };
}

type RawSetMinimoItem = readonly [
    serviceCode: string,
    serviceName: string,
    category: ServicePrescriptionCategory,
    periodicityMonths: number | null,
    sheetAndRows: string,
    conditions: readonly string[],
];

type RawSetMinimoPackage = Readonly<{
    id: string;
    prefix: string;
    title: string;
    diagnosisLabel: string;
    icd11Codes: readonly string[];
    questionPrefix: string;
    elencoRow: number;
    items: readonly RawSetMinimoItem[];
}>;

function buildDraftItem(pkg: RawSetMinimoPackage, raw: RawSetMinimoItem): DraftServicePackageItem {
    const [serviceCode, serviceName, category, periodicityMonths, sheetAndRows, appropriatenessConditions] = raw;
    const codeSlug = serviceCode.toLowerCase().replace(/[^a-z0-9]+/gu, '-');
    return {
        id: `${pkg.prefix}-${codeSlug}`,
        serviceCode,
        serviceName,
        category,
        priority: 'P',
        periodicityMonths,
        clinicalQuestion: `${pkg.questionPrefix}: ${serviceName.toLowerCase()}`,
        exemptionCode: null,
        appropriatenessConditions,
        sources: [setMinimiSource(sheetAndRows), NOMENCLATORE_2025],
    };
}

function buildDraftPackage(raw: RawSetMinimoPackage): DraftServicePackage {
    return {
        schemaVersion: LOMBARDIA_SERVICE_PACKAGE_SCHEMA,
        id: raw.id,
        territory: 'lom',
        codeSystem: LOMBARDIA_SERVICE_CODE_SYSTEM,
        title: raw.title,
        approval: { status: 'draft_pending_approval' },
        activation: {
            icd11Codes: raw.icd11Codes,
            diagnosisLabel: raw.diagnosisLabel,
        },
        exemption: null,
        sources: [setMinimiSource(`Foglio ELENCO PATOLOGIE, riga ${raw.elencoRow}`)],
        baseItems: raw.items.map((item) => buildDraftItem(raw, item)),
        complicationModules: [],
    };
}

